#!/bin/bash
cd "$(dirname "$0")"

if [ ! -d "venv" ]; then
    echo "ОШИБКА: Система не установлена."
    echo "Сначала выполните: ./install.sh"
    read -p "Нажмите Enter для выхода..."
    exit 1
fi

if [ ! -f "db.sqlite3" ]; then
    echo "ОШИБКА: файл db.sqlite3 не найден."
    echo "Запросите его у автора проекта и положите рядом с этим файлом."
    read -p "Нажмите Enter для выхода..."
    exit 1
fi

source venv/bin/activate

echo ""
echo "================================================================"
echo "  Система «Бюджет-Культура Сочи» запускается..."
echo ""
echo "  Сейчас откроется браузер."
echo "  Если не открылся — введите в адресную строку:"
echo "  http://127.0.0.1:8000"
echo ""
echo "  ВАЖНО: не закрывайте это окно во время работы!"
echo "  Для остановки нажмите Ctrl+C"
echo "================================================================"
echo ""

sleep 2
open "http://127.0.0.1:8000" 2>/dev/null || true

python manage.py runserver
