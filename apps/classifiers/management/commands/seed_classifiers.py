class Command(BaseCommand):
    help = 'Загружает базовые справочники КОСГУ и КВР в базу данных'

    def handle(self, *args, **options) -> None:
        existing_tables = connection.introspection.table_names()
        if 'classifiers_kosgu' not in existing_tables:
            raise CommandError(
                'Таблицы не найдены. Сначала выполните миграции:\n'
                '  python manage.py migrate'
            )

        self.stdout.write('Загрузка КОСГУ...')
        created_k = 0
        for code, name in KOSGU_DATA:
            _, created = KOSGU.objects.get_or_create(code=code, defaults={'name': name})
            if created:
                created_k += 1
        self.stdout.write(self.style.SUCCESS(f'  Создано КОСГУ: {created_k}'))

        self.stdout.write('Загрузка КВР...')
        created_v = 0
        for code, name in KVR_DATA:
            _, created = KVR.objects.get_or_create(code=code, defaults={'name': name})
            if created:
                created_v += 1
        self.stdout.write(self.style.SUCCESS(f'  Создано КВР: {created_v}'))

        self.stdout.write(self.style.SUCCESS('Справочники загружены успешно.'))
